% showECGonThorax(ECG,leadsys)
% This script is used to display a BSM of the amsterdam or nijmgen ssytem
% on the thorax. It is assuemd that the first 65 electrodes represent BSM
% electrodes

function [VER,ITRI,VALS]=showECGonThorax(ECG,leadsys)

if strfind(leadsys,'nim')
    [VER,ITRI] = loadNIMGEOM();
else
    [VER,ITRI] = loadAMSGEOM();
end
T=intripol(VER,ITRI,1:65);
VALS= T*ECG(1:65,:);
if  exist('qtriplot')
    a=max(max(max(abs(VALS))));
    qtriplot(VER,ITRI);
    qtriplot(VALS)
    qtriplot('funcolor rainbow');
    qtriplot(['funscale ' num2str([-a a])])
    qtriplot(['column ' num2str(find(rms(VALS) == max(rms(VALS)))-100) ])
    qtriplot('step 0.1')
    qtriplot('signal 12 0.1 0.1 0.3 0.3')
    pause(0.1)
    qtriplot('movie 20')
end



